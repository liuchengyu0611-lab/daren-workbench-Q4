function cleanMcn(val){
  const s = String(val == null ? "" : val).trim();
  if(!s) return null;
  const normalized = s.toLowerCase();
  if(["-","—","null","无"].includes(normalized) || ["-","—","null","无"].includes(s)) return null;
  return s;
}

