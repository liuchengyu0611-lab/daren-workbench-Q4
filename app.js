function normalizeCrowdLabel(label){
  return String(label == null ? "" : label).trim().toLowerCase();
}
function crowdMap(raw){
  const o={};
  if(Array.isArray(raw)){
    (META?.crowd_list||[]).forEach((k,i)=>{
      const value = Number(raw[i]);
      if(!Number.isNaN(value) && value > 0) o[k] = value/1000;
    });
    return o;
  }
  let parsed = raw;
  if(typeof raw === "string"){
    const text = raw.trim();
    if(!text) return o;
    try{ parsed = JSON.parse(text); }catch{ return o; }
  }
  if(parsed && typeof parsed === "object" && !Array.isArray(parsed)){
    Object.entries(parsed).forEach(([k,v])=>{
      const value = Number(v);
      if(!Number.isNaN(value) && value > 0) o[k] = value;
    });
  }
  return o;
}
function topCrowdLabels(raw, limit=3){
  return Object.entries(crowdMap(raw))
    .sort((a,b)=>b[1]-a[1])
    .slice(0, limit)
    .map(([label])=>label);
}
function ageMap(arr){ const o={}; (META?.age_list||[]).forEach((k,i)=>{if(arr[i])o[k]=arr[i]/1000;}); return o; }
function cityMap(flat){ const o={}; for(let i=0;i<flat.length;i+=2){ o[flat[i]]=flat[i+1]/1000; } return o; }
