function scoreRecord(r, f, indIdx){
  const tier = tierName(K(r,"tier")), per = personaName(K(r,"per")), dimList = dimValues(K(r,"dim")), dim = dimList.join('、');
  const identity = identityName(K(r,"ide"));
  const isVertical = !!f.industry && f.industry !== "其他" && dimList.includes(f.industry);

  // Hard filters
  if(f.onlyVertical && indIdx>=0 && !isVertical) return null;
  if(indIdx>=0 && f.industry !== "其他" && !isVertical) return null;
  if(f.identities.size && !f.identities.has(identity)) return null;
  if(f.tiers.size && !f.tiers.has(tier)) return null;
  if(f.personas.size && !f.personas.has(per)) return null;
  if(f.dims.size && !dimList.some(item=>f.dims.has(item))) return null;

  const crowdScores = crowdMap(K(r,"crowd"));
  const topCrowds = topCrowdLabels(K(r,"crowd"), 3).map(normalizeCrowdLabel);
  if(f.crowds.size){
    const selectedCrowds = [...f.crowds].map(normalizeCrowdLabel);
    if(!selectedCrowds.some(x => topCrowds.includes(x))) return null;
  }

  const ageScores = ageMap(K(r,"age"));
  if(f.ages.size && ![...f.ages].some(x => (ageScores[x]||0) > 0)) return null;

  const female = (K(r,"female")||0)/1000;
  const male = Math.max(0, 1 - female);
  if(f.gender==="female" && female < 0.6) return null;
  if(f.gender==="male" && male < 0.6) return null;

  const customPrice = K(r,"custom_price")||0;
  const implantPrice = K(r,"implant_price")||0;
  if((f.custom_price_min!=null || f.custom_price_max!=null) && !customPrice) return null;
  if((f.implant_price_min!=null || f.implant_price_max!=null) && !implantPrice) return null;
  if(f.custom_price_min!=null && customPrice < f.custom_price_min) return null;
  if(f.custom_price_max!=null && customPrice > f.custom_price_max) return null;
  if(f.implant_price_min!=null && implantPrice < f.implant_price_min) return null;
  if(f.implant_price_max!=null && implantPrice > f.implant_price_max) return null;

  // Scoring
  let score = 55; const reasons = [];

  // Vertical bonus
  if(indIdx>=0 && isVertical){ score += 25; reasons.push(`行业垂类达人（达人适配行业命中）`); }
  else if(indIdx>=0){ score += 3; }

  // Crowd
  if(f.crowds.size){
    const crowdEntries = Object.entries(crowdScores);
    let s=0; const hit=[];
    for(const x of f.crowds){
      const matched = crowdEntries.find(([label])=>normalizeCrowdLabel(label) === normalizeCrowdLabel(x));
      const v = matched ? matched[1] : 0;
      if(v>0){ s+=v; hit.push({x:matched[0],v}); }
    }
    score += Math.min(s*35, 25);
    if(hit.length){ hit.sort((a,b)=>b.v-a.v); reasons.push(`目标人群TOP3命中「${hit.slice(0,2).map(h=>h.x).join(' / ')}」占比 ${fmtPct(s)}`); }
  }
  // Age
  if(f.ages.size){
    let s=0; for(const x of f.ages){ s += (ageScores[x]||0); }
    score += Math.min(s*20, 15);
    if(s>0.1) reasons.push(`目标年龄段合计占比 ${fmtPct(s)}`);
  }
  // City
  if(f.cities.length){
    const cm = cityMap(K(r,"province"));
    let s=0; const hit=[];
    for(const c of f.cities){ const v=cm[c]||0; if(v>0){ s+=v; hit.push({c,v}); } }
    score += Math.min(s*40, 12);
    if(hit.length){ hit.sort((a,b)=>b.v-a.v); reasons.push(`覆盖目标省份「${hit.slice(0,3).map(h=>h.c+' '+fmtPct(h.v)).join(' · ')}」`); }
  }
  // Gender preference bonus
  if(f.gender==="female" && female>=0.75){ score += 4; }
  if(f.gender==="male" && male>=0.75){ score += 4; }

  // Reputation (tier)
  if(tier==="100-500W"||tier==="500-1000W"||tier==="1000-3000W"||tier==="3000-5000W"||tier==="5000W+") score += 3;

  if(!reasons.length){
    if(per) reasons.push(`达人粉丝画像：${per}`);
    if(dim) reasons.push(`达人适配行业：${dim}`);
  }

  score = Math.max(0, Math.min(99, Math.round(score)));

  return {r, score, reasons, isVertical, tier, per, dim, identity};
}

function runMatch(applyFilters=true){
  if(!STATE.raw) return;
  STATE.filters.client = document.getElementById("f-client").value.trim();
  STATE.filters.category = document.getElementById("f-category").value.trim();
  STATE.filters.audienceDesc = document.getElementById("f-audience-desc").value.trim();
  STATE.filters.objective = document.getElementById("f-objective").value;
  readPriceInput();
  readDateInputs();
  STATE.filters.cities = readCityInput();
  updateVerticalToggleVisibility();

  if(applyFilters){
    STATE.hasAppliedFilters = true;
  }

  if(!STATE.hasAppliedFilters){
    STATE.results = STATE.raw.records.map((r)=>({
      r,
      score: 0,
      reasons: [],
      isVertical: false,
      tier: tierName(K(r,"tier")),
      per: personaName(K(r,"per")),
      dim: dimName(K(r,"dim")),
      identity: identityName(K(r,"ide"))
    }));
    STATE.pageIndex = 0;
    renderIndustryInsights();
    renderPromoInsights();
    renderResults();
    renderStrategy();
    return;
  }

  if(!STATE.generated){
    STATE.results = STATE.raw.records.map((r)=>({
      r,
      score: 0,
      reasons: [],
      isVertical: false,
      tier: tierName(K(r,"tier")),
      per: personaName(K(r,"per")),
      dim: dimName(K(r,"dim")),
      identity: identityName(K(r,"ide"))
    }));
    STATE.pageIndex = 0;
    renderIndustryInsights();
    renderPromoInsights();
    renderResults();
    renderStrategy();
    return;
  }

  renderIndustryInsights();
  renderPromoInsights();
  const f = STATE.filters;
  const indIdx = IND_LIST.indexOf(f.industry);

  const scored = [];
  const src = STATE.raw.records;
  for(let i=0; i<src.length; i++){
    const r = src[i];
    if(f.industry === "其他"){
      if(dimValues(K(r,"dim")).length !== 0) continue;
    }
    const s = scoreRecord(r, f, indIdx);
    if(s) scored.push(s);
  }

  scored.sort((a,b)=>{
    if(indIdx >= 0 && a.isVertical !== b.isVertical) return b.isVertical - a.isVertical;
    return b.score - a.score;
  });

  STATE.results = scored;
  STATE.pageIndex = 0;
  renderResults();
  renderStrategy();
}

function renderResults(){
  const list = STATE.results.slice();
  const sortBy = document.getElementById("sort-by").value;
  const tierRank = {"5000W+":11,"3000-5000W":10,"1000-3000W":9,"500-1000W":8,"300-500W":7,"100-500W":6,"100-300W":5,"50-100W":4,"30-50W":3,"10-30W":2,"<10W":1,"":0};
  if(sortBy!=="score"){
    const sorters = {
      tier:(a,b)=>(tierRank[b.tier]||0)-(tierRank[a.tier]||0)||b.score-a.score,
      price_asc:(a,b)=>(K(a.r,"custom_price")||9e9)-(K(b.r,"custom_price")||9e9),
      price_desc:(a,b)=>(K(b.r,"custom_price")||0)-(K(a.r,"custom_price")||0),
    };
    list.sort(sorters[sortBy]);
  }

  document.getElementById("match-count").textContent = list.length;
  const vCount = STATE.hasAppliedFilters ? list.filter(x=>x.isVertical).length : 0;
  document.getElementById("vertical-count").textContent = STATE.hasAppliedFilters && vCount ? `（其中垂类 ${vCount} 位）` : '';
  const avg = STATE.hasAppliedFilters && list.length ? Math.round(list.reduce((a,b)=>a+b.score,0)/list.length) : "-";
  document.getElementById("avg-score").textContent = avg;
  const prices = list.map(x=>K(x.r,"custom_price")||0).filter(v=>v).sort((a,b)=>a-b);
  document.getElementById("median-price").textContent = prices.length ? fmtMoney(prices[Math.floor(prices.length/2)]) : "-";

  const wrap = document.getElementById("results");
  const empty = document.getElementById("empty");
  const paginationWrap = document.getElementById("pagination-wrap");
  if(!list.length){
    wrap.innerHTML="";
    empty.textContent = STATE.generated ? "暂无匹配的达人，请尝试放宽筛选条件。" : "请先填写品牌和行业信息，并点击「生成策略」。";
    empty.classList.remove("hidden");
    paginationWrap.classList.add("hidden");
    return;
  }
  empty.classList.add("hidden");

  const totalPages = Math.ceil(list.length / STATE.pageSize);
  if(STATE.pageIndex >= totalPages) STATE.pageIndex = Math.max(0, totalPages - 1);
  const start = STATE.pageIndex * STATE.pageSize;
  const pageData = list.slice(start, start + STATE.pageSize);

  wrap.innerHTML = pageData.map((r,i)=>cardHTML(r, i)).join("");
  wrap.querySelectorAll("[data-idx]").forEach(el=>el.addEventListener("click", ()=>openModal(pageData[+el.dataset.idx])));

  renderPagination(totalPages);
  paginationWrap.classList.remove("hidden");
}

function renderPagination(totalPages){
  const el = document.getElementById("pagination");
  const meta = document.getElementById("pagination-meta");
  if(!el || totalPages <= 0) return;

  const current = STATE.pageIndex;
  const maxButtons = 7;
  let pages = [];

  if(totalPages <= maxButtons){
    for(let i=0; i<totalPages; i++) pages.push(i);
  } else {
    pages.push(0);
    let start = Math.max(1, current - 2);
    let end = Math.min(totalPages - 2, current + 2);
    if(start > 1) pages.push("...");
    for(let i=start; i<=end; i++) pages.push(i);
    if(end < totalPages - 2) pages.push("...");
    pages.push(totalPages - 1);
  }

  const btnClass = "chip selectable px-3 py-1.5 min-w-[36px] flex items-center justify-center font-medium transition-all";

  let html = `<button onclick="gotoPage(${current-1})" ${current===0?'disabled':''} class="${btnClass} ${current===0?'opacity-40 cursor-not-allowed':''}">« 上一页</button>`;
  html += pages.map(p => {
    if(p === "...") return `<span class="px-2 text-[var(--ink-4)]">...</span>`;
    const activeStyle = current===p ? ` style="background:var(--brand);color:#fff;border-color:var(--brand);"` : "";
    const activeClass = current===p ? " on shadow-sm" : "";
    return `<button onclick="gotoPage(${p})" class="${btnClass}${activeClass}"${activeStyle}>${p+1}</button>`;
  }).join("");
  html += `<button onclick="gotoPage(${current+1})" ${current>=totalPages-1?'disabled':''} class="${btnClass} ${current>=totalPages-1?'opacity-40 cursor-not-allowed':''}">下一页 »</button>`;

  el.innerHTML = html;
  meta.textContent = `第 ${current + 1} / ${totalPages} 页 · 共 ${STATE.results.length.toLocaleString()} 位达人`;
}

function gotoPage(idx){
  const totalPages = Math.ceil(STATE.results.length / STATE.pageSize);
  if(idx < 0 || idx >= totalPages) return;
  STATE.pageIndex = idx;
  renderResults();
  document.getElementById("results").scrollIntoView({behavior:"smooth", block:"start"});
}

