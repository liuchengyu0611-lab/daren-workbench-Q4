function findCategoryInsight(cat){
  const input = String(cat||"").trim();
  if(!input) return null;
  const lower = input.toLowerCase();
  // 1. 精确 key
  if(CATEGORY_INSIGHTS[input]) return {key:input, ...CATEGORY_INSIGHTS[input]};
  // 2. 别名精确匹配
  for(const [key, aliases] of Object.entries(CATEGORY_INSIGHT_ALIASES)){
    if(!CATEGORY_INSIGHTS[key]) continue;
    if(aliases.some(a=>a.toLowerCase()===lower || a===input)) return {key, ...CATEGORY_INSIGHTS[key]};
  }
  // 3. 前缀感知的模糊匹配：长 key 优先，避免"护肤"→"男士护肤"
  const GENDER_SPECIES_PREFIX = /^(男士|男生|男性|女士|女生|女性|儿童|婴儿|宝宝|宠物|老年|银发|老人)/;
  const inputPref = (input.match(GENDER_SPECIES_PREFIX)||[])[0] || "";
  const keys = Object.keys(CATEGORY_INSIGHTS).sort((a,b)=>b.length-a.length);
  for(const k of keys){
    const kl = k.toLowerCase();
    const hit = input.includes(k) || k.includes(input) || lower.includes(kl) || kl.includes(lower);
    if(!hit) continue;
    const kPref = (k.match(GENDER_SPECIES_PREFIX)||[])[0] || "";
    // 前缀（性别/物种）必须一致，否则跳过
    if(inputPref !== kPref) continue;
    return {key:k, ...CATEGORY_INSIGHTS[k]};
  }
  return null;
}

