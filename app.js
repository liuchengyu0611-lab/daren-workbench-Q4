function computeCreatorMixSuggestion(list, industry){
  // 目标：当用户选择行业时，按“该行业在名单中的真实分布”给配比建议，而非全量名单整体分布
  // industry 为空时，沿用当前匹配结果 list 的分布

  const heavy = ["100-500W","100-300W","300-500W","500-1000W","1000-3000W","3000-5000W","5000W+"];
  const mid = ["30-50W","50-100W"];
  const light = ["10-30W","<10W"];

  const byTier = {};

  if(industry){
    // 使用全量池（raw）中该行业的达人 tier 分布
    const raw = STATE.raw && Array.isArray(STATE.raw.records) ? STATE.raw.records : [];
    raw.forEach(r=>{
      if(!dimValues(K(r, "dim")).includes(industry)) return;
      const t = tierName(K(r, "tier"));
      if(!t) return;
      byTier[t] = (byTier[t]||0) + 1;
    });
  } else {
    // 使用当前匹配结果 list 的 tier 分布（兜底）
    list.forEach(x=>{ if(x && x.tier) byTier[x.tier] = (byTier[x.tier]||0)+1; });
  }

  const sumOf = arr => arr.reduce((s,t)=>s+(byTier[t]||0),0);
  const hv = sumOf(heavy), md = sumOf(mid), lg = sumOf(light);
  const total = hv+md+lg;
  if(!total) return {items:[], note: industry ? `该行业暂无达人数据，无法给出配比建议` : "暂无匹配达人，无法给出配比建议"};

  const items = [
    {name:"头部（100W+）", count:hv, ratio:hv/total},
    {name:"腰部（30W-100W）", count:md, ratio:md/total},
    {name:"尾部（<30W）", count:lg, ratio:lg/total},
  ];

  let note = industry
    ? `基于「${industry}」行业达人池分布：推荐 头部 1-2 位打声量 + 腰部 3-5 位承接讨论 + 尾部 10 位以上放量收割，兼顾破圈与转化效率。`
    : "推荐 头部 1-2 位打声量 + 腰部 3-5 位承接讨论 + 尾部 10 位以上放量收割，兼顾破圈与转化效率。";

  if(hv/total > 0.6) note = industry
    ? `「${industry}」头部占比偏高，建议加码腰部/尾部达人承接内容长尾与真实种草。`
    : "头部占比偏高，建议加码腰部/尾部达人承接内容长尾与真实种草。";
  else if(lg/total > 0.7) note = industry
    ? `「${industry}」尾部占比偏高，可视预算加入 1-2 位头部达人拉升声量与信任度。`
    : "尾部占比偏高，可视预算加入 1-2 位头部达人拉升声量与信任度。";

  return {items, note};
}
function computeCategoryStrategy(insight, list){
  if(!insight) return null;
  const cr = {}; const ag = {}; const persona = {}; let totalFemale=0;
  list.forEach(x=>{
    const c = crowdMap(K(x.r,"crowd"));
    Object.entries(c).forEach(([k,v])=>{ cr[k] = (cr[k]||0)+v; });
    const a = ageMap(K(x.r,"age"));
    Object.entries(a).forEach(([k,v])=>{ ag[k] = (ag[k]||0)+v; });
    if(x.per) persona[x.per] = (persona[x.per]||0)+1;
    totalFemale += (K(x.r,"female")||0)/1000;
  });
  const topPersona = Object.entries(persona).sort((a,b)=>b[1]-a[1]).slice(0,2).map(x=>x[0]);
  const topCrowd = Object.entries(cr).sort((a,b)=>b[1]-a[1]).slice(0,2).map(x=>x[0]);
  const topAge = Object.entries(ag).sort((a,b)=>b[1]-a[1]).slice(0,2).map(x=>x[0]);
  const averageFemale = list.length ? totalFemale / list.length : 0;
  const genderBias = list.length ? (averageFemale >= 0.5 ? "女粉为主" : "男粉为主") : "";
  return {insight, topPersona, topCrowd, topAge, genderBias};
}

