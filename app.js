function getPromoInsightsData(){
  const rawStart = STATE.filters.dateStart || "";
  const rawEnd = STATE.filters.dateEnd || "";
  if(!rawStart && !rawEnd){
    return {hasRange:false, start:"", end:"", nodes:[], strategies:[]};
  }
  let start = parseDateValue(rawStart || rawEnd);
  let end = parseDateValue(rawEnd || rawStart);
  if(!start || !end){
    return {hasRange:false, start:"", end:"", nodes:[], strategies:[]};
  }
  if(start > end){ const temp = start; start = end; end = temp; }
  const nodes = [];
  const seen = new Set();
  const cursor = new Date(start);
  let guard = 0;
  while(cursor <= end && guard < 420){
    const md = toMMDD(cursor);
    PROMO_CALENDAR.forEach(node=>{
      if(!seen.has(node.name) && isPromoNodeHit(node, cursor, md)){
        seen.add(node.name);
        nodes.push(node.name);
      }
    });
    cursor.setDate(cursor.getDate()+1);
    guard += 1;
  }
  return {
    hasRange:true,
    start:formatDateValue(start),
    end:formatDateValue(end),
    nodes,
    strategies:buildPromoStrategies(STATE.filters.industry, nodes)
  };
}
function formatPromoPeriod(data){
  if(!data?.hasRange) return "未设置";
  return data.start === data.end ? data.start : `${data.start} ~ ${data.end}`;
}
