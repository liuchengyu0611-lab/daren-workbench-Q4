function getBrandStrategyProfile(brand){
  const input=String(brand||"").trim().toLowerCase();
  if(!input) return null;
  return BRAND_STRATEGY_PROFILES.find(profile=>[profile.name,...(profile.aliases||[])].some(name=>input.includes(String(name).toLowerCase())||String(name).toLowerCase().includes(input)))||null;
}

function getSubcategoryStrategyProfile(category, brandProfile){
  if(brandProfile?.categoryKey){
    const forced=SUBCATEGORY_STRATEGY_PROFILES.find(profile=>profile.key===brandProfile.categoryKey);
    if(forced) return forced;
  }
  const input=String(category||"").trim();
  if(!input) return null;
  return SUBCATEGORY_STRATEGY_PROFILES.find(profile=>profile.patterns.some(pattern=>pattern.test(input)))||null;
}

